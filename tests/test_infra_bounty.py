from __future__ import annotations

import re
from pathlib import Path

import pytest

from tests.test_tls import _render_role_template

ROOT = Path(__file__).parents[1]
ERROR_CODES = (413, 429, 502, 503, 504)


def _configs() -> dict[str, str]:
    return {
        "nginx.conf": (ROOT / "nginx/nginx.conf").read_text(),
        "nginx.behind-proxy.conf": (ROOT / "nginx/nginx.behind-proxy.conf").read_text(),
        "nginx.conf.j2": _render_role_template("nginx.conf.j2"),
    }


@pytest.mark.parametrize("name", ["nginx.conf", "nginx.behind-proxy.conf", "nginx.conf.j2"])
def test_every_proxying_server_gives_nginxs_own_errors_the_security_headers(name: str) -> None:
    """A 429, 413 or 502 generated by nginx never passed the app's SecurityMiddleware: it
    carried no HSTS, CSP, X-Frame-Options or Cache-Control (measured with curl -D-)."""
    text = _configs()[name]
    servers = [
        s for s in re.findall(r"\n    server \{.*?\n    \}", text, re.S) if "proxy_pass" in s
    ]
    assert servers
    for server in servers:
        assert "include /etc/nginx/snippets/error-pages.conf;" in server, name
    assert "map $server_port $ow_hsts" in text
    # No HSTS on the plain-HTTP onion listener (RFC 6797 §8.1), as in the app.
    assert re.search(r'8080\s+"";', text)


def test_the_error_snippets_cover_every_nginx_error_and_every_header() -> None:
    pages = (ROOT / "nginx/snippets/error-pages.conf").read_text()
    headers = (ROOT / "nginx/snippets/error-headers.conf").read_text()
    for code in ERROR_CODES:
        assert f"error_page {code} @ow_err_{code};" in pages
        assert re.search(
            rf"location @ow_err_{code} \{{[^}}]*error-headers\.conf;[^}}]*return {code};", pages
        )
    for header in (
        "Strict-Transport-Security $ow_hsts",
        "Content-Security-Policy",
        "X-Frame-Options",
        "X-Content-Type-Options",
        "Referrer-Policy",
        "Cache-Control",
    ):
        assert re.search(rf"add_header {re.escape(header)}\b.* always;", headers), header
    # Only nginx's own errors: proxied responses keep the app's headers, never doubled.
    assert "proxy_intercept_errors on" not in pages
