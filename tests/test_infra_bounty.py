"""Infrastructure findings of the v2.3.0 bug bounty: nginx, image, chart, Ansible, CI."""

from __future__ import annotations

import re
from pathlib import Path

import pytest

from tests.test_tls import _render_role_template

ROOT = Path(__file__).parents[1]
ERROR_CODES = (413, 429, 502, 503, 504)


def _configs() -> dict[str, str]:
    return {
        "nginx.conf": (ROOT / "nginx/nginx.conf").read_text(),
        "nginx.behind-proxy.conf": (ROOT / "nginx/nginx.behind-proxy.conf").read_text(),
        "nginx.conf.j2": _render_role_template("nginx.conf.j2"),
    }


@pytest.mark.parametrize("name", ["nginx.conf", "nginx.behind-proxy.conf", "nginx.conf.j2"])
def test_every_proxying_server_gives_nginxs_own_errors_the_security_headers(name: str) -> None:
    """A 429, 413 or 502 generated by nginx never passed the app's SecurityMiddleware: it
    carried no HSTS, CSP, X-Frame-Options or Cache-Control (measured with curl -D-)."""
    text = _configs()[name]
    servers = [
        s for s in re.findall(r"\n    server \{.*?\n    \}", text, re.S) if "proxy_pass" in s
    ]
    assert servers
    for server in servers:
        assert "include /etc/nginx/snippets/error-pages.conf;" in server, name
    assert "map $server_port $ow_hsts" in text
    # No HSTS on the plain-HTTP onion listener (RFC 6797 §8.1), as in the app.
    assert re.search(r'8080\s+"";', text)


def test_the_error_snippets_cover_every_nginx_error_and_every_header() -> None:
    pages = (ROOT / "nginx/snippets/error-pages.conf").read_text()
    headers = (ROOT / "nginx/snippets/error-headers.conf").read_text()
    for code in ERROR_CODES:
        assert f"error_page {code} @ow_err_{code};" in pages
        assert re.search(
            rf"location @ow_err_{code} \{{[^}}]*error-headers\.conf;[^}}]*return {code};", pages
        )
    for header in (
        "Strict-Transport-Security $ow_hsts",
        "Content-Security-Policy",
        "X-Frame-Options",
        "X-Content-Type-Options",
        "Referrer-Policy",
        "Cache-Control",
    ):
        assert re.search(rf"add_header {re.escape(header)}\b.* always;", headers), header
    # Only nginx's own errors: proxied responses keep the app's headers, never doubled.
    assert "proxy_intercept_errors on" not in pages


def test_the_app_code_in_the_image_is_not_writable_by_the_runtime_user() -> None:
    """`COPY --chown=openwhistle` made /app/app/main.py writable by uid 1000: `echo x >>
    /app/app/main.py` succeeded in the running image (podman run, before the fix)."""
    final = (ROOT / "Dockerfile").read_text().split("AS final", 1)[1]
    assert not re.search(r"(?m)^(COPY|ADD)\b[^\n]*--chown", final), "the code must stay root-owned"
    assert re.search(
        r"(?m)^RUN chmod -R go-w,a\+rX \. \\\n\s+&& /venv/bin/python -B scripts/generate_integrity",
        final,
    )
    assert final.index("USER openwhistle") > final.index("chmod -R go-w")


def test_the_chart_starts_slowly_and_meets_pod_security_restricted() -> None:
    """The server listens only after `alembic upgrade head` (connection refused for the whole
    migration, measured with a 20 s alembic wrapper): without a startupProbe the liveness
    probe killed the pod after 15 + 3 x 30 s. `restricted` also wants a seccomp profile, and
    the app needs no service-account token."""
    import yaml

    chart = ROOT / "charts/openwhistle"
    text = (chart / "templates/deployment.yaml").read_text()
    rendered = text
    # Rendered with helm when it is there; otherwise the template text is the contract.
    import shutil
    import subprocess

    if helm := shutil.which("helm"):
        args = ["--set", "secrets.secretKey=" + "x" * 40, "--set", "secrets.databaseUrl=d"]
        args += ["--set", "secrets.redisUrl=r"]
        out = subprocess.run(  # noqa: S603
            [
                helm,
                "template",
                "ow",
                str(chart),
                "--show-only",
                "templates/deployment.yaml",
                *args,
            ],
            capture_output=True,
            text=True,
            check=True,
        ).stdout
        rendered = out
        spec = yaml.safe_load(out)["spec"]["template"]["spec"]
        container = spec["containers"][0]
        assert spec["automountServiceAccountToken"] is False
        assert spec["securityContext"]["seccompProfile"] == {"type": "RuntimeDefault"}
        startup = container["startupProbe"]
        assert startup["httpGet"]["path"] == "/health"
        assert startup["periodSeconds"] * startup["failureThreshold"] >= 300
    assert "automountServiceAccountToken: false" in rendered
    assert "type: RuntimeDefault" in rendered
    assert "startupProbe:" in rendered


def test_the_docker_sdk_comes_from_the_distribution_not_from_pip() -> None:
    """`pip3 install docker` as root on debian:12 stops with externally-managed-environment
    (PEP 668), so the role failed on Debian 12 and Ubuntu 24.04. community.docker needs it."""
    import yaml

    tasks = yaml.safe_load((ROOT / "ansible/roles/openwhistle/tasks/docker.yml").read_text())
    assert not [t for t in tasks if "ansible.builtin.pip" in t or "pip" in t], "pip install"
    packages = [p for t in tasks for p in (t.get("ansible.builtin.apt") or {}).get("name", [])]
    assert "python3-docker" in packages


def test_the_ansible_tls_block_has_the_same_tls_directives_as_the_bundled_nginx() -> None:
    """The template lacked `ssl_session_tickets off` (openssl s_client showed a 86400 s ticket
    lifetime hint there, none on the bundled nginx), and used 1d and another cache zone."""

    def tls(text: str) -> dict[str, str]:
        block = next(
            s for s in re.findall(r"\n    server \{.*?\n    \}", text, re.S) if "ssl_" in s
        )
        found = re.findall(r"(?m)^\s*(ssl_(?!certificate)\w+)\s+([^;]+);", block)
        return dict(found)

    bundled = tls((ROOT / "nginx/nginx.conf").read_text())
    template = tls(_render_role_template("nginx.conf.j2"))
    assert bundled["ssl_session_tickets"] == "off"
    assert template == bundled
